# Two Types of Typecasting:

# Explicit Conversion (Explicit type casting in python)  = 
# The conversion of one data type into another data type done via developer or programmer's intervention or manually

# Implicit Conversion (Implicit type casting in python)  =
# Data types in Python do not have the same level 

var1 = 1.2
var2 = 2

print (int(var1) + int(var2))  # Explicit Conversion
print (str(var1) + str(var2))

print (var1 + var2)             # Implicit Conversion